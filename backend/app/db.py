"""Postgres access (psycopg 3). One shared autocommit connection guarded by an RLock (request threads + job worker).

SQL keeps '?' placeholders; they are translated to %s here (literal '%' is escaped when params are given).
Schema migrations: SCHEMA below is version 1 (CREATE ... IF NOT EXISTS, so init() is idempotent). To change the schema
later, append (version, sql) to MIGRATIONS; init() applies the ones above the stored schema_version in order.
"""
import threading
from contextlib import contextmanager
import psycopg
from psycopg.rows import dict_row
from . import config as C

SCHEMA = """
CREATE TABLE IF NOT EXISTS schema_version(version INT NOT NULL);
CREATE TABLE IF NOT EXISTS verses(
  id TEXT PRIMARY KEY, title TEXT NOT NULL, text JSONB NOT NULL,           -- text: JSON list of lines
  source_work TEXT NOT NULL, source_reference TEXT NOT NULL,
  source_url TEXT, source_edition TEXT, notes TEXT, meter_hint TEXT,
  origin TEXT NOT NULL DEFAULT 'user', created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS meters(
  id TEXT PRIMARY KEY, name TEXT, wav TEXT, ref_text TEXT, syllable_count INT, sec_per_syll REAL, is_prose BOOLEAN);
CREATE TABLE IF NOT EXISTS voices(
  id TEXT PRIMARY KEY, name TEXT, checkpoint TEXT, vocoder TEXT, notice TEXT, enabled BOOLEAN DEFAULT TRUE);
CREATE TABLE IF NOT EXISTS jobs(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, verse_id TEXT NOT NULL REFERENCES verses(id),
  meter_id TEXT NOT NULL, voice_id TEXT NOT NULL, executor TEXT NOT NULL, device TEXT NOT NULL,
  steps INT NOT NULL, seed INT NOT NULL,
  status TEXT NOT NULL DEFAULT 'queued', progress REAL DEFAULT 0, log TEXT DEFAULT '', error TEXT,
  created_at TIMESTAMPTZ DEFAULT now(), started_at TIMESTAMPTZ, finished_at TIMESTAMPTZ,
  batch_id BIGINT);   -- batch_id also added by migration 3 for older databases
CREATE TABLE IF NOT EXISTS assets(      -- *_key are object-storage keys, e.g. jobs/<id>/chant.mp3
  job_id BIGINT PRIMARY KEY REFERENCES jobs(id), mp3_key TEXT, wav_key TEXT, alignment_key TEXT, duration REAL);
CREATE TABLE IF NOT EXISTS settings(key TEXT PRIMARY KEY, value TEXT);
CREATE TABLE IF NOT EXISTS word_meanings(
  verse_id TEXT NOT NULL REFERENCES verses(id) ON DELETE CASCADE, line_idx INT NOT NULL, word_idx INT NOT NULL,
  word_text TEXT NOT NULL, meaning TEXT NOT NULL, grammar TEXT,
  origin TEXT NOT NULL DEFAULT 'user', reviewed BOOLEAN NOT NULL DEFAULT FALSE, updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY(verse_id, line_idx, word_idx));
CREATE TABLE IF NOT EXISTS verse_summaries(
  verse_id TEXT PRIMARY KEY REFERENCES verses(id) ON DELETE CASCADE, translation TEXT NOT NULL, explanation TEXT,
  origin TEXT NOT NULL DEFAULT 'user', reviewed BOOLEAN NOT NULL DEFAULT FALSE, updated_at TIMESTAMPTZ NOT NULL DEFAULT now());
"""
BASE_VERSION = 1      # version of SCHEMA above
_EPICS_SQL = """
CREATE TABLE IF NOT EXISTS epic_sargas(
  epic TEXT NOT NULL, kanda INT NOT NULL, sarga INT NOT NULL, data JSONB NOT NULL, PRIMARY KEY(epic, kanda, sarga));
CREATE TABLE IF NOT EXISTS epic_verses(
  id TEXT PRIMARY KEY, epic TEXT NOT NULL, kanda INT NOT NULL, sarga INT NOT NULL, seq INT NOT NULL, kind TEXT, data JSONB NOT NULL);
CREATE INDEX IF NOT EXISTS epic_verses_pos ON epic_verses(epic, kanda, sarga, seq);
"""
_BATCH_SQL = """
CREATE TABLE IF NOT EXISTS epic_batches(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, epic TEXT NOT NULL, scope JSONB, voice_id TEXT, steps INT, seed INT,
  device TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT now());
ALTER TABLE jobs ADD COLUMN IF NOT EXISTS batch_id BIGINT;
CREATE INDEX IF NOT EXISTS jobs_batch ON jobs(batch_id);
"""
MIGRATIONS: list[tuple[int, str]] = [(2, _EPICS_SQL), (3, _BATCH_SQL)]
VERSION = max([BASE_VERSION] + [v for v, _ in MIGRATIONS])   # latest schema version      # (version, sql) applied in order when version > stored schema_version
DEFAULT_SETTINGS = {"executor": "local", "device": "cpu", "steps": str(C.DEFAULT_STEPS),
                    "colab_drive_dir": "", "colab_timeout_s": "3600", "colab_manual_timeout_s": "86400"}
_lock = threading.RLock()
search_path: str | None = None      # tests set this to a throwaway schema name before reset_connection()

def connect():
    kw = {"options": f"-c search_path={search_path}"} if search_path else {}
    return psycopg.connect(C.DATABASE_URL, autocommit=True, row_factory=dict_row, **kw)

_con = None
def db():
    global _con
    if _con is None or _con.closed:
        _con = connect()
    return _con

def reset_connection():
    global _con
    with _lock:
        if _con is not None:
            try: _con.close()
            except Exception: pass
        _con = None

def _sql(sql, args):
    if not args: return sql, None
    return sql.replace("%", "%%").replace("?", "%s"), tuple(args)

@contextmanager
def tx():
    with _lock:
        with db().transaction():      # nested use becomes a savepoint
            yield db()

def q(sql, args=()):
    with _lock:
        s, a = _sql(sql, args)
        return db().execute(s, a).fetchall()

def q1(sql, args=()):
    r = q(sql, args); return r[0] if r else None

def x(sql, args=()):
    with _lock:
        s, a = _sql(sql, args)
        return db().execute(s, a)

def init():
    from backend.engine.meter import load_bank
    with _lock:
        db().execute(SCHEMA)
        cur = q1("SELECT max(version) v FROM schema_version")["v"]
        if cur is None:
            x("INSERT INTO schema_version VALUES(?)", (BASE_VERSION,)); cur = BASE_VERSION
        for ver, sql in MIGRATIONS:
            if ver > cur:
                with tx(): db().execute(sql); x("UPDATE schema_version SET version=?", (ver,))
        for k, v in DEFAULT_SETTINGS.items():
            x("INSERT INTO settings VALUES(?,?) ON CONFLICT DO NOTHING", (k, v))
        for m in load_bank():
            x("INSERT INTO meters VALUES(?,?,?,?,?,?,?) ON CONFLICT (id) DO UPDATE SET name=EXCLUDED.name, wav=EXCLUDED.wav,"
              " ref_text=EXCLUDED.ref_text, syllable_count=EXCLUDED.syllable_count, sec_per_syll=EXCLUDED.sec_per_syll,"
              " is_prose=EXCLUDED.is_prose",
              (m["id"], m["name"], m["wav"], m["ref_text"], m["syllable_count"], m["sec_per_syll"], bool(m["is_prose"])))
        notice = "Synthetic voice modelled on a reciter; not a recording of the speaker."
        for vid, name, ck in [("steer", "Vāgdhenu steer (default)", "voice_steer_ema_2026-06-17.pt"),
                              ("armA", "Vāgdhenu armA", "voice_armA_ema_2026-06-11.pt")]:
            x("INSERT INTO voices VALUES(?,?,?,?,?,TRUE) ON CONFLICT DO NOTHING",
              (vid, name, str(C.MODELS / ck), str(C.MODELS / "voc_bigvgan_EMA_2026-06-11.pth"), notice))

def set_setting(key, value):
    x("INSERT INTO settings VALUES(?,?) ON CONFLICT (key) DO UPDATE SET value=EXCLUDED.value", (key, str(value)))

def get_settings() -> dict:
    return {r["key"]: r["value"] for r in q("SELECT * FROM settings")}
